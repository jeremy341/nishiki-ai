// Builds pond-multi.js from the vendored koi engine with ONE extra feature, for the home mockup:
// opts.dim() may return an ARRAY of clearings, each either a rect {left,top,right,bottom} or a circle {cx,cy,r},
// with an optional own fade distance {fade} and floor {min}. Open-water marks (caustics, sparkles) fade there too.
// opts.count fixes the number of koi (the engine otherwise picks it from the screen area).
// Everything else is the unchanged engine. Run: node docs/mockups/make-pond-multi.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
let s = fs.readFileSync(path.resolve(here, "../../client/src/vendor/ascii-koi/pond.js"), "utf8");
const swap = (a, b) => { if (!s.includes(a)) throw new Error("missing: " + a.slice(0, 40)); s = s.replace(a, b); };
swap(`const box = opts.dim ? opts.dim() : null, pad = cw * 8;
      const dimAt = box ? (x, y) => {
        const d = Math.hypot(Math.max(box.left - x, 0, x - box.right), Math.max(box.top - y, 0, y - box.bottom));
        return 0.1 + 0.9 * sstep(0, pad, d);
      } : () => 1;`,
`const raw = opts.dim ? opts.dim() : null, boxes = raw ? [].concat(raw) : [], pad = cw * 8;
      const dimAt = boxes.length ? (x, y) => {
        let m = 1;
        for (const b of boxes) {
          const d = b.r !== undefined ? Math.max(0, Math.hypot(x - b.cx, y - b.cy) - b.r)
            : Math.hypot(Math.max(b.left - x, 0, x - b.right), Math.max(b.top - y, 0, y - b.bottom));
          const lo = b.min === undefined ? 0.1 : b.min;
          m = Math.min(m, lo + (1 - lo) * sstep(0, b.fade || pad, d));
        }
        return m;
      } : () => 1;`);
swap(`if (cl > 0.8) { ctx.globalAlpha = (cl - 0.8) * 1.3;`, `if (cl > 0.8) { ctx.globalAlpha = (cl - 0.8) * 1.3 * dimAt(x, y) ** 2;`);
swap(`ctx.globalAlpha = 0.1 + 0.12 * (0.5 + 0.5 * Math.sin(t * 0.9 + h * 900));`, `ctx.globalAlpha = (0.1 + 0.12 * (0.5 + 0.5 * Math.sin(t * 0.9 + h * 900))) * dimAt(x, y) ** 2;`);
swap(`const count = () => Math.round(room(vw, vh, MOST));`, `const count = () => opts.count || Math.round(room(vw, vh, MOST));`);
fs.writeFileSync(path.resolve(here, "pond-multi.js"), "/* GENERATED by make-pond-multi.mjs from client/src/vendor/ascii-koi/pond.js (MIT, pursurer/ascii-koi). Do not edit. */\n" + s);
console.log("pond-multi.js written");
